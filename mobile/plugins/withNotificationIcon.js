const { withDangerousMod } = require('expo/config-plugins');
const fs = require('fs');
const path = require('path');

/**
 * Expo config plugin: write the monochrome status-bar/notification icon.
 *
 * The first-party Media3 service needs a small icon for the media notification
 * (and Android Auto attribution). A launcher icon renders as a white square
 * there, so we ship the logo's set steps as a white-on-transparent
 * VectorDrawable that Android tints to match the system. The drawable is
 * generated from web/public/Logo.svg by scripts/generate_brand_assets.mjs and
 * referenced as `smallIcon: 'ic_stat_music'` in player setup.
 */
const ICON_SOURCE = ['plugins', 'brand', 'ic_stat_music.xml'];

function readIcon(projectRoot) {
  const source = path.join(projectRoot, ...ICON_SOURCE);
  if (!fs.existsSync(source)) {
    throw new Error(
      `Notification icon is missing: ${source}. Run npm run generate:brand-assets in mobile/.`,
    );
  }
  const xml = fs.readFileSync(source, 'utf8');
  if (!xml.includes('<vector ') || !xml.includes('android:pathData="M')) {
    throw new Error(`Notification icon ${source} is not a VectorDrawable with path data`);
  }
  return xml;
}

/**
 * Media3's DefaultMediaNotificationProvider shows `media3_notification_small_icon`
 * (a play circle by default) in the status bar and media card. Apps override it
 * by redefining that drawable, so alias it to the logo icon.
 */
const MEDIA3_SMALL_ICON_OVERRIDE = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/withNotificationIcon.js: Media3 notification small icon = LoggeRythm logo. -->
<resources>
  <drawable name="media3_notification_small_icon">@drawable/ic_stat_music</drawable>
</resources>
`;

/** Write the logo icon and the Media3 small-icon alias into an Android res/ directory. */
function writeNotificationIcon(projectRoot, resourceRoot) {
  const drawables = path.join(resourceRoot, 'drawable');
  const values = path.join(resourceRoot, 'values');
  fs.mkdirSync(drawables, { recursive: true });
  fs.mkdirSync(values, { recursive: true });
  fs.writeFileSync(path.join(drawables, 'ic_stat_music.xml'), readIcon(projectRoot));
  fs.writeFileSync(path.join(values, 'media3_notification_icon.xml'), MEDIA3_SMALL_ICON_OVERRIDE);
}

function withNotificationIcon(config) {
  return withDangerousMod(config, [
    'android',
    async (cfg) => {
      writeNotificationIcon(
        cfg.modRequest.projectRoot,
        path.join(cfg.modRequest.platformProjectRoot, 'app', 'src', 'main', 'res'),
      );
      return cfg;
    },
  ]);
}

module.exports = withNotificationIcon;
module.exports.writeNotificationIcon = writeNotificationIcon;
